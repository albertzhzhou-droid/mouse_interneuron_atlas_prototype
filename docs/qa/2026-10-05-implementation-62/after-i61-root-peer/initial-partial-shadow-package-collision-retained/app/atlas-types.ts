type NeuromorphoCensusMainSceneRecord = (typeof neuromorphoCensusMainSceneIndexJson.records)[number];

function censusRecordToObservedCellForm(record: NeuromorphoCensusMainSceneRecord) {
  const secondaryLabels = record.sourceMetadata.cellTypeLabels.slice(1);
  const secondaryClass = secondaryLabels[0]?.toLowerCase();
  return {
    neuronId: record.neuronId,
    assetId: record.assetId,
    phenotype: secondaryLabels.join(" · ") || record.sourceMetadata.cellTypeLabels[0] || "Interneuron label not reported",
    transmitter: secondaryClass === "excitatory"
      ? "excitatory" as const
      : secondaryClass === "inhibitory"
        ? "inhibitory" as const
        : "mixed_or_unspecified" as const,
    domain: record.sourceMetadata.domain,
    physicalIntegrity: record.sourceMetadata.physicalIntegrity,
    sourcePaperDoi: record.sourcePaper.dois[0] ?? "",
    segmentCount: record.geometry.segmentCount,
    geometryStatus: "OBS" as const,
    sourceFrame: record.sourceMetadata.sourceFrame,
    registrationStatus: "unregistered" as const,
  };
}

function censusRecordToMorphologyFidelity(record: NeuromorphoCensusMainSceneRecord) {
  const radius = record.geometry.radiusEvidence;
  const sourceRadiusAvailable = record.geometry.sourceDiameterAvailable && radius !== null;
  const radiusSurfaceAvailable = sourceRadiusAvailable && record.geometry.dimensionality === "3D";
  return {
    neuronId: record.neuronId,
    assetId: record.assetId,
    geometry: {
      path: record.geometry.path,
      bytes: record.geometry.bytes,
      sha256: record.geometry.sha256,
      rawSwcSha256: record.geometry.rawSwcSha256,
      geometryStatus: "OBS_STANDARDIZED_SOURCE_LOCAL" as const,
      sourceFrame: record.sourceMetadata.sourceFrame,
      dimensionality: record.geometry.dimensionality,
      sourceDiameterAvailable: record.geometry.sourceDiameterAvailable,
      nodeCount: record.geometry.nodeCount,
      segmentCount: record.geometry.segmentCount,
    },
    axon: {
      sourceType2NodeCount: record.geometry.nodeTypeCounts["2"] ?? 0,
      sourceDomain: record.sourceMetadata.domain,
      completeAxon: false as const,
    },
    radiusEvidence: {
      status: sourceRadiusAvailable ? "OBSERVED_SOURCE_RADIUS" as const : "UNAVAILABLE" as const,
      minimumMicrometre: sourceRadiusAvailable ? radius.minimumMicrometre : null,
      maximumMicrometre: sourceRadiusAvailable ? radius.maximumMicrometre : null,
      meanMicrometre: sourceRadiusAvailable ? radius.meanMicrometre : null,
      missingReason: sourceRadiusAvailable ? null : "official_attributes_report_no_diameter",
    },
    modes: {
      observedSwc: { available: true as const, authority: "OBS_STANDARDIZED_SOURCE_LOCAL" as const },
      radiusSurface: {
        available: radiusSurfaceAvailable,
        authority: radiusSurfaceAvailable ? "DERIVED_FROM_OBSERVED_RADIUS" as const : "UNAVAILABLE" as const,
        missingReason: radiusSurfaceAvailable
          ? null
          : record.geometry.dimensionality === "2D" && sourceRadiusAvailable
            ? "source_geometry_is_2d_no_3d_surface_authorized"
            : "official_attributes_report_no_diameter",
      },
      internalStructure: {
        available: false as const,
        authority: "UNAVAILABLE" as const,
        missingEvidence: ["membrane_segmentation", "nucleus", "organelles", "synaptic_boutons", "receptor_distribution", "ultrastructure"],
      },
    },
  };
}

