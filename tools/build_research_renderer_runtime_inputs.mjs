const check = (ok, message) => { if (!ok) throw new Error(`Renderer runtime inputs: ${message}`); };
export function buildRendererRuntimeInputs(authoritativeInputs) {
  check(Array.isArray(authoritativeInputs), "canonical inputs are missing");
  const rows = RUNTIME_RENDERER_INPUT_PATHS.map(relative => {
    const matching = authoritativeInputs.filter(row => row.path === relative);
    check(matching.length === 1, `canonical input is missing or duplicated: ${relative}`);
    const row = matching[0];
    check(Number.isSafeInteger(row.bytes) && row.bytes > 0 && /^[a-f0-9]{64}$/.test(row.sha256), `canonical byte pin is invalid: ${relative}`);
    return { path: row.path, bytes: row.bytes, sha256: row.sha256 };
  });
  return { schemaVersion: "0.1.0", applicationVersion: "2.91.0-research.1", scope: "exact_current_renderer_and_auxiliary_input_pins", authoritativeInputs: rows };
}
export function rendererRuntimeInputsBytes(authoritativeInputs) {
  return Buffer.from(JSON.stringify(buildRendererRuntimeInputs(authoritativeInputs), null, 2) + "\n");
}
export function validateRendererRuntimeInputs(actual, authoritativeInputs) {
  check(JSON.stringify(actual) === JSON.stringify(buildRendererRuntimeInputs(authoritativeInputs)), "transport differs from exact canonical runtime pins");
  return { inputCount: actual.authoritativeInputs.length, canonicalPinsUnchanged: true, scientificSourceAdmissionChanged: false };
}
